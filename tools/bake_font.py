"""Bake the pinned JetBrains Mono ASCII subset; Pillow is build-time only."""
from pathlib import Path
import hashlib
import json

ROOT=Path(__file__).resolve().parents[1]
FONT=ROOT/'assets/fonts/jetbrains-mono/JetBrainsMono-Regular.ttf'
EXPECTED='a0bf60ef0f83c5ed4d7a75d45838548b1f6873372dfac88f71804491898d138f'

def main():
    import PIL
    from PIL import Image,ImageDraw,ImageFont
    raw=FONT.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=EXPECTED:raise ValueError('Font differs from pinned JetBrains Mono 2.304')
    font=ImageFont.truetype(str(FONT),28,layout_engine=ImageFont.Layout.BASIC)
    ascent,descent=font.getmetrics();height=ascent+descent
    bounds=[font.getbbox(chr(c),anchor='ls') for c in range(32,127)]
    width=max(max(b[2] for b in bounds),int(font.getlength('M')))
    if min(b[0] for b in bounds)<0 or min(b[1] for b in bounds)<-ascent or max(b[3] for b in bounds)>descent:
        raise ValueError('Glyph clipping would occur')
    pitch=(width+1)//2;atlas=bytearray()
    for code in range(32,127):
        cell=Image.new('L',(width,height),0)
        ImageDraw.Draw(cell).text((0,ascent),chr(code),font=font,fill=255,anchor='ls',stroke_width=0)
        pixels=cell.load()
        for y in range(height):
            for x in range(0,width,2):
                hi=(pixels[x,y]*15+127)//255
                lo=(pixels[x+1,y]*15+127)//255 if x+1<width else 0
                atlas.append((hi<<4)|lo)
    metrics=ROOT/'include/kbl/generated/jetbrains_mono_metrics.hpp';metrics.parent.mkdir(parents=True,exist_ok=True)
    metrics.write_text('// Generated by tools/bake_font.py. Glyph data: SIL Open Font License 1.1.\n#pragma once\nnamespace kbl {\n'+
        f'constexpr unsigned font_cell_width={width}, font_cell_height={height}, font_baseline={ascent};\n'+
        '} // namespace kbl\n',encoding='utf-8')
    license=(FONT.parent/'OFL.txt').read_text(encoding='utf-8')
    data=ROOT/'src/generated/jetbrains_mono_data.hpp';data.parent.mkdir(parents=True,exist_ok=True)
    lines=['// Generated from JetBrains Mono 2.304. Font data is licensed under SIL OFL 1.1.',
        '// Copyright 2020 The JetBrains Mono Project Authors. See assets/fonts/jetbrains-mono/OFL.txt.',
        '#pragma once','#include <stdint.h>','namespace kbl::font_data {',
        f'constexpr unsigned pitch={pitch};','constexpr uint8_t coverage[]={']
    for start in range(0,len(atlas),24):lines.append('    '+','.join('0x%02x'%x for x in atlas[start:start+24])+',')
    lines+=['};','constexpr char license[]=R"KBL_FONT('+license+')KBL_FONT";','} // namespace kbl::font_data','']
    data.write_text('\n'.join(lines),encoding='utf-8')
    manifest={'family':'JetBrains Mono Regular','release':'2.304','source_url':
        'https://github.com/JetBrains/JetBrainsMono/blob/v2.304/fonts/ttf/JetBrainsMono-Regular.ttf',
        'font_sha256':EXPECTED,'license':'SIL Open Font License 1.1','pillow_version':PIL.__version__,
        'pixel_size':28,'cell_width':width,'cell_height':height,'baseline':ascent,
        'glyph_range':[32,126],'coverage_bits':4,'atlas_bytes':len(atlas),'atlas_sha256':hashlib.sha256(atlas).hexdigest()}
    (FONT.parent/'baked.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    print('Baked JetBrains Mono: %dx%d cells, %d antialiased glyphs, %d bytes'%(width,height,95,len(atlas)))

if __name__=='__main__':main()
